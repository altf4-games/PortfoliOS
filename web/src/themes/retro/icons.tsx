ART.projects = ART.folder;

function normalize(art: Art): string[] {
  const rows = art.slice(0, 16);
  while (rows.length < 16) rows.push("");
  return rows.map((r) => (r + ".".repeat(16)).slice(0, 16));
}

const PixelArt = memo(function PixelArt({ name, className }: { name: string; className?: string }) {
  const rows = normalize(ART[name] ?? ART.file);
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const ch = row[x];
      if (ch === "." || !PALETTE[ch]) {
        x++;
        continue;
      }
      // Merge horizontal runs of the same color into one rect.
      let run = 1;
      while (x + run < 16 && row[x + run] === ch) run++;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={run} height={1} fill={PALETTE[ch]} />);
      x += run;
    }
  });
  return (
    <svg viewBox="0 0 16 16" className={className} shapeRendering="crispEdges" aria-hidden="true">
      {rects}
    </svg>
  );
});

export function PixelIcon({ id, className }: { id: WindowId | "folder" | "file" | "link" | "logo"; className?: string }) {
  return <PixelArt name={id} className={className} />;
}
